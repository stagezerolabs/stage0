import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const contractsRoot = resolve(
  process.env.SMART_CONTRACTS_DIR ?? resolve(process.cwd(), "../../Reactpad-tests/smart-contracts"),
);

const artifactPaths = {
  PresaleFactory: "out/PresaleFactory.sol/PresaleFactory.json",
  PresaleContract: "out/LaunchpadPresale.sol/WhitelistedLaunchpadPresale.json",
  TokenFactory: "out/TokenFactory.sol/TokenFactory.json",
  TokenLocker: "out/TokenLocker.sol/TokenLocker.json",
  AirdropMultiSender: "out/AirdropMultisender.sol/AirdropMultisender.json",
  NFTFactory: "out/NFTFactory.sol/NFTFactory.json",
  NFTFactoryLens: "out/NFTFactoryLens.sol/NFTFactoryLens.json",
  RNSRegistry: "out/RNSRegistryV2.sol/RNSRegistryV2.json",
  RNSResolver: "out/RNSResolverV2.sol/RNSResolverV2.json",
  RNSRegistrar: "out/RNSRegistrarV2.sol/RNSRegistrarV2.json",
  RNSAuctionHouse: "out/RNSAuctionHouse.sol/RNSAuctionHouse.json",
  RNSMarketplaceEscrow: "out/RNSMarketplaceEscrow.sol/RNSMarketplaceEscrow.json",
};

async function readAbi(relativePath) {
  const artifact = JSON.parse(await readFile(resolve(contractsRoot, relativePath), "utf8"));
  if (!Array.isArray(artifact.abi)) {
    throw new Error(`Artifact has no ABI: ${relativePath}`);
  }
  return artifact.abi;
}

function canonicalType(parameter) {
  if (!parameter.type?.startsWith("tuple")) return parameter.type;
  const suffix = parameter.type.slice("tuple".length);
  return `(${(parameter.components ?? []).map(canonicalType).join(",")})${suffix}`;
}

function abiKey(item) {
  if (item.type === "constructor" || item.type === "fallback" || item.type === "receive") {
    return item.type;
  }
  return `${item.type}:${item.name ?? ""}(${(item.inputs ?? []).map(canonicalType).join(",")})`;
}

function mergeAbis(...abis) {
  const merged = new Map();
  for (const abi of abis) {
    for (const item of abi) {
      const key = abiKey(item);
      if (!merged.has(key)) merged.set(key, item);
    }
  }
  return [...merged.values()];
}

const abis = Object.fromEntries(
  await Promise.all(
    Object.entries(artifactPaths).map(async ([name, artifactPath]) => [name, await readAbi(artifactPath)]),
  ),
);

const launchpadNftAbi = mergeAbis(
  await readAbi("out/NFTSales.sol/LaunchpadNFTEth.json"),
  await readAbi("out/NFTSales721A.sol/LaunchpadNFT721AEth.json"),
);

const generatedHeader = `// This file is generated by npm run sync:abis. Do not edit by hand.\n`;
const generatedSource = [
  generatedHeader,
  ...Object.entries({
    ...abis,
    NFTCollectionContract: launchpadNftAbi,
  }).map(([name, abi]) => `export const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`),
].join("\n");

const generatedTarget = resolve(process.cwd(), "src/lib/contracts/generatedAbis.ts");
const indexerTargets = {
  "indexer/goldsky/rise-launchpad/abis/PresaleFactory.json": abis.PresaleFactory,
  "indexer/goldsky/rise-launchpad/abis/LaunchpadPresale.json": abis.PresaleContract,
  "indexer/goldsky/rise-launchpad/abis/NFTFactory.json": abis.NFTFactory,
  "indexer/goldsky/rise-launchpad/abis/LaunchpadNFT.json": launchpadNftAbi,
  "indexer/goldsky/rns/abis/RNSRegistry.json": abis.RNSRegistry,
  "indexer/goldsky/rns/abis/RNSResolver.json": abis.RNSResolver,
  "indexer/goldsky/rns/abis/RNSRegistrar.json": abis.RNSRegistrar,
};

const serializedTargets = new Map([
  [generatedTarget, generatedSource],
  ...Object.entries(indexerTargets).map(([target, abi]) => [
    resolve(process.cwd(), target),
    `${JSON.stringify(abi, null, 2)}\n`,
  ]),
]);

if (process.argv.includes("--check")) {
  const staleTargets = [];
  for (const [target, expected] of serializedTargets) {
    const actual = await readFile(target, "utf8").catch(() => null);
    if (actual !== expected) staleTargets.push(target.replace(`${process.cwd()}/`, ""));
  }

  if (staleTargets.length > 0) {
    throw new Error(`Stale contract ABIs:\n${staleTargets.map((target) => `- ${target}`).join("\n")}`);
  }

  console.log(`Verified ${serializedTargets.size} generated ABI targets.`);
} else {
  await mkdir(resolve(process.cwd(), "src/lib/contracts"), { recursive: true });
  await Promise.all(
    [...serializedTargets].map(([target, source]) => writeFile(target, source)),
  );

  console.log(`Synced ${Object.keys(abis).length + 1} frontend ABIs and ${Object.keys(indexerTargets).length} indexer ABIs.`);
}
